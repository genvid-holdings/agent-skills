def walk_assets(root: Path, include_other: bool):
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS and not d.startswith("."))
        for name in sorted(filenames):
            if name.startswith("."):
                continue
            path = Path(dirpath) / name
            ext = path.suffix.lower()
            if ext in MODALITY_BY_EXT:
                yield path
            elif include_other and path.is_file():
                yield path


class ScanError(Exception):
    """The scan could not run at all (as opposed to running and finding gaps)."""


def scan(root: Path, declaration_path=None, max_bytes=DEFAULT_MAX_BYTES, include_other=False):
    declaration, decl_path, decl_error = _load_declaration(root, declaration_path)
    if decl_error and declaration_path:
        # Explicitly named by the operator: refusing is right, because silently
        # scanning without it would answer a different question than the one asked.
        raise ScanError("cannot read declaration %s: %s" % (decl_path, decl_error))

    assets = []
    unreadable = []
    for path in walk_assets(root, include_other):
        if decl_path and path == decl_path:
            continue
        try:
            assets.append(assess_asset(path, root, declaration, max_bytes))
        except (OSError, struct.error) as exc:
            unreadable.append({"path": path.relative_to(root).as_posix(), "error": str(exc)})

    gaps = production_gaps(declaration, decl_path, assets, decl_error)
    for asset in assets:
        gaps.extend(find_gaps(asset))

    disclosure_files = sorted(
        p.name for p in root.iterdir()
        if p.is_file() and p.name.lower() in DISCLOSURE_NAMES
    ) if root.is_dir() else []

    counts = {
        "assets_scanned": len(assets),
        "unreadable": len(unreadable),
        "synthetic_or_indicated": sum(1 for a in assets if a["origin"].startswith("synthetic") or a["origin"] == "contested"),
        "origin_undetermined": sum(1 for a in assets if a["origin"] == "undetermined"),
        "machine_readable_marking_present": sum(1 for a in assets if a["disclosure"]["machine_readable_marking"] == "present"),
        "gaps": len(gaps),
        "gaps_by_severity": {
            level: sum(1 for g in gaps if g["severity"] == level) for level in ("high", "medium", "low")
        },
    }

    return {
        "schema": REPORT_SCHEMA,
        "tool": {"name": TOOL_NAME, "version": TOOL_VERSION, "network_calls": 0, "account_required": False},
        "generated_at": _dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "scope": {
            "root": str(root),
            "declaration": decl_path.name if (decl_path and not decl_error) else None,
            "declaration_error": decl_error,
            "disclosure_files": disclosure_files,
            "regulation": "Regulation (EU) 2024/1689, Article 50",
            "applies_from": ARTICLE_APPLIES_FROM,
            "article_50_2_transition_ends": ARTICLE_50_2_TRANSITION_ENDS,
        },
        "limits": [
            "This tool reports evidence found in the files themselves. It does not determine compliance and its output is not legal advice.",
            "Imperceptible watermarks are not assessed. Metadata inspection cannot substitute for the detector that matches the embedder, so a second marking layer can be declared here but never confirmed.",
            "Content-credential detection is presence-only: signatures and trust chains are not validated.",
            "Origin calls for assets with no declaration entry rest on metadata a generating tool happened to leave behind, which any transcode, screenshot or re-encode removes.",
            "Article 50(2) and Article 50(4) are separate axes. A machine-readable marking does not discharge the deep-fake disclosure duty, because such markings are not clear and distinguishable to the people exposed to the content.",
            "Generative systems placed on the market before the application date have a transitional period for the Article 50(2) marking and detection obligations only. Whether that applies to any given system is a question about the system, not about these files.",
            "The formats this tool reads (content credentials, IPTC digital source type) are de-facto industry implementations. Neither is named in the Regulation, the Commission guidelines, or the code of practice, none of which mandates any specific standard.",
        ],
        "counts": counts,
        "assets": assets,
        "unreadable": unreadable,
        "gaps": gaps,
    }


def render_gap_list(report) -> str:
    counts = report["counts"]
    lines = [
        "# Article 50 gap list",
        "",
        "Scope: `%s`" % report["scope"]["root"],
        "Generated: %s by %s %s" % (report["generated_at"], report["tool"]["name"], report["tool"]["version"]),
        "Reference: %s, applies from %s" % (report["scope"]["regulation"], report["scope"]["applies_from"]),
        "",
        "This is a work list built from what the files carry. It is not a compliance",
        "determination and it is not legal advice.",
        "",
        "## Where the directory stands",
        "",
        "| Measure | Count |",
        "| --- | ---: |",
        "| Assets scanned | %d |" % counts["assets_scanned"],
        "| Reading as generated or manipulated | %d |" % counts["synthetic_or_indicated"],
        "| Origin undetermined | %d |" % counts["origin_undetermined"],
        "| Carrying machine-readable marking | %d |" % counts["machine_readable_marking_present"],
        "| Gaps recorded | %d (high %d, medium %d, low %d) |" % (
            counts["gaps"],
            counts["gaps_by_severity"]["high"],
            counts["gaps_by_severity"]["medium"],
            counts["gaps_by_severity"]["low"],
        ),
        "",
    ]

    if not report["gaps"]:
        lines += ["## Gaps", "", "No gaps recorded. That means nothing was found to flag in these bytes,",
                  "not that an obligation has been met.", ""]
    else:
        lines += ["## Gaps", ""]
        for level in ("high", "medium", "low"):
            batch = [g for g in report["gaps"] if g["severity"] == level]
            if not batch:
                continue
            lines += ["### %s (%d)" % (level.capitalize(), len(batch)), ""]
            for gap in batch:
                where = gap["asset"] or "(whole directory)"
                lines += [
                    "- **%s**, `%s`: %s" % (gap["reference"], where, gap["finding"]),
                    "  - id: `%s`" % gap["id"],
                    "  - do: %s" % gap["remediation"],
                ]
            lines.append("")

    lines += ["## What this scan did not check", ""]
    lines += ["- %s" % limit for limit in report["limits"]]
    lines.append("")
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog=TOOL_NAME,
        description="Scan a local directory of media assets for EU AI Act Article 50 transparency evidence. "
                    "No account, no network, no upload.",
    )
    parser.add_argument("path", help="directory to scan")
    parser.add_argument("-o", "--out", metavar="DIR",
                        help="write article50-disclosure-report.json and article50-gaps.md into DIR")
    parser.add_argument("--json", metavar="PATH", help="write the machine-readable report here ('-' for stdout)")
    parser.add_argument("--gaps", metavar="PATH", help="write the gap list here ('-' for stdout)")
    parser.add_argument("--declaration", metavar="PATH", help="operator declaration (default: article50.json in PATH)")
    parser.add_argument("--include-other", action="store_true",
                        help="also assess files whose extension is not a known media type")
    parser.add_argument("--max-bytes", type=int, default=DEFAULT_MAX_BYTES,
                        help="per-end read budget for large files (default %d)" % DEFAULT_MAX_BYTES)
    parser.add_argument("--exit-zero", action="store_true", help="exit 0 even when gaps are recorded")
    args = parser.parse_args(argv)

    root = Path(args.path).expanduser().resolve()
    if not root.is_dir():
        print("article50_scan: not a directory: %s" % root, file=sys.stderr)
        return 2

    try:
        report = scan(root, args.declaration, args.max_bytes, args.include_other)
    except ScanError as exc:
        print("article50_scan: %s" % exc, file=sys.stderr)
        return 2
    gap_list = render_gap_list(report)
    report_json = json.dumps(report, indent=2, sort_keys=False) + "\n"

    wrote = []
    if args.out:
        outdir = Path(args.out).expanduser().resolve()
        outdir.mkdir(parents=True, exist_ok=True)
        (outdir / "article50-disclosure-report.json").write_text(report_json, encoding="utf-8")
        (outdir / "article50-gaps.md").write_text(gap_list, encoding="utf-8")
        wrote += [str(outdir / "article50-disclosure-report.json"), str(outdir / "article50-gaps.md")]
    if args.json:
        if args.json == "-":
            sys.stdout.write(report_json)
        else:
            Path(args.json).expanduser().write_text(report_json, encoding="utf-8")
            wrote.append(args.json)
    if args.gaps:
        if args.gaps == "-":
            sys.stdout.write(gap_list)
        else:
            Path(args.gaps).expanduser().write_text(gap_list, encoding="utf-8")
            wrote.append(args.gaps)

    if not (args.out or args.json or args.gaps):
        sys.stdout.write(gap_list)
    elif wrote:
        print("article50_scan: wrote %s" % ", ".join(wrote), file=sys.stderr)

    if report["counts"]["gaps"] and not args.exit_zero:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
