def _json_type(value) -> str:
    """The JSON name for a decoded value, so a shape error reads as JSON, not Python."""
    for kind, name in ((bool, "boolean"), (str, "string"), (dict, "object"),
                       (list, "array"), (int, "number"), (float, "number")):
        if isinstance(value, kind):
            return name
    return "null" if value is None else type(value).__name__


def _a_json_type(value) -> str:
    return "%s %s" % ("an" if _json_type(value)[0] in "aeiou" else "a", _json_type(value))


def _shape_error(data):
    """Why this decoded declaration cannot be read, or None if it can.

    Valid JSON of the wrong shape is as unusable as JSON that does not parse, and
    it used to reach the assessment and raise AttributeError from deep inside it:
    an unhandled traceback, exit 1 (the "gaps found" code) and no artifacts, so a
    CI gate reported a finding and then found no report to read. Every shape the
    reader later assumes is checked here instead, once, where the existing
    unparsable-declaration handling can carry it.
    """
    if not isinstance(data, dict):
        return "the declaration must be a JSON object, not %s" % _a_json_type(data)
    for key in ("production", "defaults", "assets"):
        value = data.get(key)
        if value is not None and not isinstance(value, dict):
            return "the declaration's %s must be a JSON object, not %s" % (key, _a_json_type(value))
    for name, entry in sorted((data.get("assets") or {}).items()):
        if not isinstance(entry, dict):
            return ("the declaration's entry for %s must be a JSON object, not %s" %
                    (name, _a_json_type(entry)))
    return None


def _load_declaration(root: Path, explicit):
    """Load the operator declaration. Returns (data, path, error)."""
    candidates = [Path(explicit)] if explicit else [root / name for name in DECLARATION_NAMES]
    for candidate in candidates:
        if candidate.is_file():
            try:
                data = json.loads(candidate.read_text(encoding="utf-8"))
            except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
                # A file that is not valid UTF-8 is the same condition as a file
                # that is not valid JSON -- present, and unreadable as a
                # declaration -- and it has the same designed answer: the
                # declaration-unparsable gap, and a scan that still runs against
                # file metadata alone. UnicodeDecodeError is a ValueError, not an
                # OSError, so it used to escape this handler, scan() and main(),
                # and one stray byte killed the process before any report existed.
                return None, candidate, str(exc)
            shape = _shape_error(data)
            if shape:
                return None, candidate, shape
            return data, candidate, None
    if explicit:
        # "Present but not a file" and "not there at all" want different
        # repairs from the operator, and only one of them was ever reported:
        # is_file() is false for a directory too, so `--declaration ./somedir`
        # fell through to the missing-path message and told an operator who had
        # pointed at the right place that nothing was there.
        path = Path(explicit)
        if path.is_dir():
            return None, path, "that is a directory, not a declaration file"
        if path.exists():
            return None, path, "that is not a regular file"
        return None, path, "declaration file not found"
    return None, None, None


def _declared_bool(declared, field):
    """Read a declaration field DECLARATION.md types as a boolean.

    Returns (value, malformed) where `value` is True, False or None, and
    `malformed` describes what was there instead when the field is present but
    not a boolean. Identity tests against True and False used to fall through
    silently for every other value, so `"ai_generated": "true"` dropped the
    Article 50(2) duty and the marking gap with it, while `bool()` on
    `"deep_fake": "false"` read the string as a declared deep fake.
    """
    if field not in declared:
        return None, None
    value = declared[field]
    if value is None or isinstance(value, bool):
        return value, None
    return None, "%s (%s)" % (json.dumps(value)[:80], _a_json_type(value))


def _declaration_key_index(assets):
    """Each key's normalisation form to its first spelling in sorted order.

    Built once per scan and reused for every asset. Re-deriving it inside
    _declared_for sorted and normalised the whole assets map on every lookup
    that fell through to the normalisation match -- and with `defaults`
    carrying most productions, falling through is the common case, so a flat
    directory cost O(assets^2 log assets) on the same shape of miss the
    StemIndex fix removed for sidecars. Sorted order kept so a declaration
    holding both spellings resolves the same way every run.
    """
    index = {}
    for key in sorted(assets):
        index.setdefault(_match_key(_declared_key(key)), key)
    return index


def _declared_for(declaration, relpath: str, key_index=None):
    if not declaration:
        return {}
    assets = declaration.get("assets") or {}
    entry = assets.get(relpath)
    if entry is None:
        entry = assets.get("./" + relpath)
    if entry is None:
        # Same characters, other normalisation form.
        if key_index is None:
            key_index = _declaration_key_index(assets)
        key = key_index.get(_match_key(relpath))
        if key is not None:
            entry = assets[key]
    merged = dict(declaration.get("defaults") or {})
    if isinstance(entry, dict):
        merged.update(entry)
    return merged


def _has_text(value) -> bool:
    """True when a declaration field carries wording a person could be shown.

    These fields are defined as the words that appear on screen, in the credits
    or in the player, so only a non-empty string qualifies. Bare truthiness let
    three separate non-answers discharge an Article 50(4) duty: `"   "` (the
    artifact of a form writing a space where it meant to omit the key), `true`,
    and any nonzero number. None of them is wording anyone is shown.
    """
    return bool(_text(value))


def _text(value) -> str:
    """The wording a declaration field carries, trimmed; empty when it carries none.

    The same rule as `_has_text`, for the callers that need the words rather
    than the fact that there are some. Kept as one definition so a field cannot
    read as present here and absent there.
    """
    return value.strip() if isinstance(value, str) else ""


# Characters that are structure or terminal instruction rather than wording.
# Line breaks and vertical space end a Markdown block; the rest are obeyed by a
# terminal or a renderer without appearing as text.
_RENDER_BREAKS = "\t\n\r\v\f\x1c\x1d\x1e\x1f\x85"

# The gap list is a work list a person reads, and every value the declaration
# puts in it is operator-authored and unbounded. A declared 2,000,000-character
# title rendered as a 2 MB single-line heading. Two budgets, because the two
# kinds of value are read for different reasons: `title`, `operator` and `role`
# identify the report, so anything past a generous heading's worth adds nothing,
# while an asset path is what the operator has to act on, so it gets room for a
# deeply nested real one -- Linux caps a path at 4096 bytes, and a declaration
# key is only bounded by the declaration.
RENDER_TEXT_LIMIT = 200
RENDER_PATH_LIMIT = 1024
# ASCII, deliberately. stdout is not always UTF-8 (a set PYTHONIOENCODING, a
# minimal container, a Windows codepage), a write that cannot encode is exit 2,
# and this mark is appended to values the operator may have written in pure
# ASCII -- a one-character ellipsis would have made a long plain title the
# reason an all-ASCII production could not be reported on at all.
RENDER_TRUNCATION_MARK = "..."


def _render_safe(value, limit=None) -> str:
    """One line of wording, with nothing in it a renderer or a terminal obeys.

    `title`, `operator` and `role` are written by the party whose claims this
    scan exists to cross-check against the bytes, and they reach the Markdown
    gap list a person reads. Unfiltered, a newline in one of them closed the
    heading and opened a forged `## Gaps` block reading "No gaps recorded", an
    unclosed `<!--` swallowed the rest of the document in any CommonMark
    renderer, and an ESC sequence cleared the terminal of anyone who `cat`-ed
    the file over the real findings. Asset paths reach the same surface and a
    filename may legally hold the same bytes.

    This is a rendering rule, not a rewrite of the record: `scope.production`
    still carries what the operator wrote, character for character, because the
    JSON report escapes it on the way out. Unpaired surrogates are deliberately
    left alone -- they are a value UTF-8 cannot encode at all, which is a
    delivery failure the write guard in `main` reports as exit 2 rather than
    something to paper over here.

    `limit` bounds the rendered result for the callers whose value comes from
    the declaration. The cut is marked rather than silent, because a shortened
    title otherwise reads as the operator's own wording, and it is applied after
    neutralisation so the budget counts characters a reader actually sees.
    """
    kept = []
    for ch in str(value):
        category = unicodedata.category(ch)
        # Zl and Zp are the Unicode line and paragraph separators, spelled by
        # category rather than by literal so they stay legible in this source.
        if ch in _RENDER_BREAKS or category in ("Zl", "Zp"):
            kept.append(" ")
        elif category in ("Cc", "Cf"):
            continue
        else:
            kept.append(ch)
    rendered = " ".join("".join(kept).split())
    if limit is not None and len(rendered) > limit:
        return rendered[:limit] + RENDER_TRUNCATION_MARK
    return rendered


def _code_span(text: str) -> str:
    """`text` as a Markdown code span, so a renderer shows it and obeys none of it.

    Fenced with one more backtick than the longest run inside it, per
    CommonMark; a value that opens or closes with a backtick is padded, which
    the renderer strips again.
    """
    fence = "`" * (max((len(run) for run in re.findall(r"`+", text)), default=0) + 1)
    pad = " " if text.startswith("`") or text.endswith("`") else ""
    return "%s%s%s%s%s" % (fence, pad, text, pad, fence)


def _declared_text_entries(declaration):
    """The merged declaration entries whose key names a text asset.

    Article 50(4)'s second subparagraph reaches published text, so both limbs
    read from here: the disclosure that discharges the duty and the review that
    lifts it. The declaration's own entries are read rather than the assessed
    assets, so a declared text file that never reached the disk still carries
    its record.
    """
    defaults = declaration.get("defaults") or {}
    texts = []
    for key, entry in (declaration.get("assets") or {}).items():
        if MODALITY_BY_EXT.get(os.path.splitext(key)[1].lower()) != "text":
            continue
        merged = dict(defaults)
        if isinstance(entry, dict):
            merged.update(entry)
        texts.append(merged)
    return texts


def _review_recorded(declaration, production) -> bool:
    """Whether human review of the published AI text is on record.

    Article 50(4)'s second subparagraph lifts the disclosure duty only where the
    text underwent human review or editorial control AND someone holds editorial
    responsibility. This answers the first limb, and only that limb.

    Scoped to text, because that is what the paragraph covers: an image asset's
    review status says nothing about whether the published article was read by a
    person. An explicit `human_review: false` on any declared text is decisive
    and outranks a positive record elsewhere -- a publication containing AI text
    the operator states nobody reviewed is not a publication the exemption
    reaches, and the operator setting the field to false said exactly that.

    The declaration's own entries are read rather than the assessed assets, so a
    declared text file that never reached the disk still carries its record.
    """
    texts = _declared_text_entries(declaration)

    if production.get("human_review") is False or any(t.get("human_review") is False for t in texts):
        return False
    if production.get("human_review") is True:
        return True
    # `defaults` is deliberately not consulted on its own. DECLARATION.md defines
    # it as a per-asset default -- it applies to every asset and is overridden per
    # entry -- not as a statement about the publication, and it is already merged
    # into each entry above. So a real default has reached `texts` by now; reading
    # it separately would only ever fire where there is no text to default, which
    # is precisely where it is wrong: a review flag covering the production's
    # images would clear the duty on text nobody read.
    return any(t.get("human_review") is True for t in texts)


def _declared_key(key: str) -> str:
    """Normalise a declaration asset key to the relative-path form the walk yields.

    Shared by reconciliation and by the scan's in-scope test. If those two ever
    disagreed about what "declared" means, a declared path could be in scope for
    one and not the other, and go unexamined with nothing saying so -- the exact
    failure the rest of this file is built to prevent.
    """
    return key[2:] if key.startswith("./") else key


def _match_key(path: str) -> str:
    """The form two paths are compared in: the same characters, one spelling.

    The declaration is typed on a keyboard or pasted from a spreadsheet, which
    produces NFC; the file is written by whatever pipeline made it, and several
    ordinary macOS write paths produce NFD. `café_shot.png` in those two forms
    is one filename with two byte sequences, and comparing them raw made the
    report say both that the asset was scanned and that no file was found at
    it -- two flatly contradictory statements about the same bytes, with the
    declaration's `ai_generated: true` dropped between them.

    Normalisation is not case folding and does not soften the exact-case rule:
    NFC/NFD are two encodings of one character, `A` and `a` are two characters.
    """
    return unicodedata.normalize("NFC", path)


def unmatched_declarations(declaration, assessed, on_disk, skipped_dirs=()):
    """Declared assets that no scanned file accounts for.

    A declaration key matching nothing the walk found used to vanish from the
    report entirely, so whether the file happened to exist -- not what the
    declaration said about it -- decided the outcome, and a typo discharged every
    duty attached to the asset silently.

    ``on_disk`` is the set of paths the walk actually saw, so membership is an
    exact, case-sensitive comparison. Asking the filesystem instead (Path.is_file)
    would answer differently on a case-insensitive volume and make the report
    platform-dependent, which is how a key differing only in case reads as a file
    present under an unreadable extension on macOS and as absent on Linux.

    ``skipped_dirs`` names the directories the walk pruned (SKIP_DIRS). A key
    underneath one is absent from ``on_disk`` for a reason that has nothing to
    do with the file: it is there and readable, and the scan declined to look.
    Recording which directory withheld it is what stops the gap describing a
    delivered file as one that was never delivered.

    The entry's booleans are typed here exactly as a matched asset's are. This
    used to hand the raw JSON straight to the production-level 50(4) check,
    where a bare truth test read the string "false" -- a non-empty string -- as
    a declared deep fake. DECLARATION.md types these fields at both levels with
    no carve-out for an entry that never reached disk, and the whole point of
    the rule is that a value which is neither true nor false resolves nothing.
    """
    if not declaration:
        return []
    folded = {}
    on_disk_match = set()
    for path in sorted(on_disk):
        probe = _match_key(path)
        on_disk_match.add(probe)
        folded.setdefault(probe.lower(), path)
    assessed_match = {_match_key(path) for path in assessed}

    unmatched = []
    for key, entry in sorted((declaration.get("assets") or {}).items()):
        relpath = _declared_key(key)
        probe = _match_key(relpath)
        if probe in assessed_match:
            continue
        merged = dict(declaration.get("defaults") or {})
        if isinstance(entry, dict):
            merged.update(entry)
        booleans = {field: _declared_bool(merged, field)
                    for field in DECLARED_BOOLEAN_FIELDS}
        present = probe in on_disk_match
        unmatched.append({
            "path": relpath,
            "declared": merged,
            "deep_fake": booleans["deep_fake"][0] is True,
            # Present in the entry but not of the documented type. Reported by
            # declared_asset_gaps rather than coerced, the same as a matched
            # asset's, so the operator hears the same answer wherever the file is.
            "malformed_fields": {field: bad for field, (_, bad) in booleans.items() if bad},
            "on_disk": present,
            "case_match": None if present else folded.get(probe.lower()),
            "withheld_by": next(
                (d for d in skipped_dirs if probe.startswith(_match_key(d) + "/")), None),
        })
    return unmatched


