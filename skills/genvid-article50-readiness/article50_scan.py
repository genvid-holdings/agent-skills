def _read_edges(path: Path, max_bytes: int):
    """Return (head, tail, size). Metadata boxes cluster at both ends."""
    size = path.stat().st_size
    with path.open("rb") as fh:
        if size <= max_bytes * 2:
            data = fh.read()
            return data, b"", size
        head = fh.read(max_bytes)
        fh.seek(-max_bytes, os.SEEK_END)
        tail = fh.read(max_bytes)
    return head, tail, size


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for block in iter(lambda: fh.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _extract_xmp(blob: bytes) -> str:
    """Return every XMP packet in ``blob`` as one decoded string."""
    packets = []
    start = blob.find(XMP_OPEN)
    while start != -1 and len(packets) < 8:
        end = blob.find(XMP_CLOSE, start)
        if end == -1:
            packets.append(blob[start:start + 200000].decode("utf-8", "replace"))
            break
        packets.append(blob[start:end + len(XMP_CLOSE)].decode("utf-8", "replace"))
        start = blob.find(XMP_OPEN, end)
    return "\n".join(packets)


def _png_chunks(blob: bytes):
    """Yield (type, payload) for each PNG chunk. Tolerates truncation."""
    if not blob.startswith(b"\x89PNG\r\n\x1a\n"):
        return
    pos = 8
    limit = len(blob)
    while pos + 8 <= limit:
        (length,) = struct.unpack(">I", blob[pos:pos + 4])
        ctype = blob[pos + 4:pos + 8]
        start = pos + 8
        end = start + length
        if length > limit or end > limit:
            return
        yield ctype, blob[start:end]
        pos = end + 4
        if ctype == b"IEND":
            return


def _bmff_boxes(blob: bytes):
    """Yield (type, payload) for top-level ISO-BMFF boxes. Tolerates truncation."""
    pos = 0
    limit = len(blob)
    while pos + 8 <= limit:
        (size,) = struct.unpack(">I", blob[pos:pos + 4])
        btype = blob[pos + 4:pos + 8]
        header = 8
        if size == 1:
            if pos + 16 > limit:
                return
            (size,) = struct.unpack(">Q", blob[pos + 8:pos + 16])
            header = 16
        elif size == 0:
            size = limit - pos
        if size < header:
            return
        end = pos + size
        yield btype, blob[pos + header:min(end, limit)]
        if end <= pos or end > limit:
            return
        pos = end


def _riff_chunks(blob: bytes):
    """Yield (fourcc, payload) for RIFF (WebP) chunks."""
    if not (blob.startswith(b"RIFF") and blob[8:12] == b"WEBP"):
        return
    pos = 12
    limit = len(blob)
    while pos + 8 <= limit:
        fourcc = blob[pos:pos + 4]
        (length,) = struct.unpack("<I", blob[pos + 4:pos + 8])
        start = pos + 8
        end = start + length
        if end > limit:
            return
        yield fourcc, blob[start:end]
        pos = end + (length & 1)


def _jpeg_segments(blob: bytes):
    """Yield (marker, payload) for JPEG APPn/COM segments."""
    if not blob.startswith(b"\xff\xd8"):
        return
    pos = 2
    limit = len(blob)
    while pos + 4 <= limit:
        if blob[pos] != 0xFF:
            pos += 1
            continue
        marker = blob[pos + 1]
        if marker in (0xD8, 0x01) or 0xD0 <= marker <= 0xD7:
            pos += 2
            continue
        if marker == 0xDA:  # start of scan; metadata is behind us
            return
        (length,) = struct.unpack(">H", blob[pos + 2:pos + 4])
        start = pos + 4
        end = pos + 2 + length
        if end > limit or length < 2:
            return
        yield marker, blob[start:end]
        pos = end


def _exif_software(payload: bytes):
    """Pull IFD0 Software (0x0131) / Artist (0x013B) out of an EXIF payload."""
    if payload.startswith(b"Exif\x00\x00"):
        payload = payload[6:]
    if len(payload) < 8:
        return {}
    if payload[:2] == b"II":
        endian = "<"
    elif payload[:2] == b"MM":
        endian = ">"
    else:
        return {}
    try:
        (offset,) = struct.unpack(endian + "I", payload[4:8])
        if offset + 2 > len(payload):
            return {}
        (count,) = struct.unpack(endian + "H", payload[offset:offset + 2])
        found = {}
        for i in range(min(count, 512)):
            entry = offset + 2 + i * 12
            if entry + 12 > len(payload):
                break
            tag, ftype, num = struct.unpack(endian + "HHI", payload[entry:entry + 8])
            if tag not in (0x0131, 0x013B, 0x010E) or ftype != 2:
                continue
            if num <= 4:
                raw = payload[entry + 8:entry + 8 + num]
            else:
                (voff,) = struct.unpack(endian + "I", payload[entry + 8:entry + 12])
                raw = payload[voff:voff + num]
            text = raw.split(b"\x00", 1)[0].decode("utf-8", "replace").strip()
            if text:
                found[{0x0131: "software", 0x013B: "artist", 0x010E: "description"}[tag]] = text
        return found
    except (struct.error, IndexError, KeyError):
        return {}


