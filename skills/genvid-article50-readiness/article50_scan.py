"""Article 50 readiness scan for a local directory of media assets.

Walks a directory, reads what each file actually carries in its own bytes
(content credentials, XMP, IPTC digital source type, generator metadata,
sidecars), reconciles that against an operator-authored declaration, and emits:

  1. a machine-readable disclosure report (JSON), and
  2. a gap list (Markdown) naming every asset whose transparency posture is
     unresolved and what would resolve it.

WHAT THIS TOOL IS NOT
---------------------
It does not decide whether anyone complies with anything. Compliance under
Regulation (EU) 2024/1689 turns on facts this tool cannot see: who the
provider is, who the deployer is, what was actually generated by whom, and how
the content is presented to people. This tool reports evidence and the absence
of evidence. Every conclusion it prints is scoped to "what is present in these
bytes". Read the gap list as a work list, not as a verdict, and route the
result past someone qualified to give legal advice.

It also cannot see imperceptible watermarks. Detecting a watermark requires the
detector that matches the embedder; no metadata read can stand in for that. The
report says so explicitly on every asset rather than scoring the axis silently.

Stdlib only. No network. No account. Python 3.9+.

Usage:
    python3 article50_scan.py PATH [-o OUTDIR] [--json PATH] [--gaps PATH]
                                   [--declaration PATH] [--max-bytes N]

Exit codes:
    0  scan completed, no gaps recorded
    1  scan completed, one or more gaps recorded
    2  the scan could not run (bad path, unreadable declaration)
"""
