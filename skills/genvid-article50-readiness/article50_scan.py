def render_gap_list(report) -> str:
    counts = report["counts"]
    # A handed-on report is otherwise identified only by `Scope:`, an absolute
    # filesystem path meaningful to nobody who did not run the scan.
    # title and operator are declared, not verified -- see scope.production --
    # so they are named in the heading rather than asserted as fact. Either or
    # both may be absent; nothing is invented to fill the gap.
    #
    # Both are operator-authored, so both are neutralised on the way in and
    # shown as code spans: a declaration could otherwise end the heading with a
    # newline and open a forged `## Gaps` section reading "No gaps recorded",
    # or start an `<!--` that hides every real finding from a renderer.
    production = report["scope"].get("production") or {}
    title = _render_safe(production.get("title") or "", RENDER_TEXT_LIMIT)
    operator = _render_safe(production.get("operator") or "", RENDER_TEXT_LIMIT)
    identity = (([_code_span(title)] if title else [])
                + (["operator: %s" % _code_span(operator)] if operator else []))
    heading = "# Article 50 gap list"
    if identity:
        heading += ": %s" % " -- ".join(identity)
    lines = [
        heading,
        "",
        "Scope: %s" % _code_span(_render_safe(report["scope"]["root"])),
        "Generated: %s by %s %s" % (report["generated_at"], report["tool"]["name"], report["tool"]["version"]),
        "Reference: %s, applies from %s" % (report["scope"]["regulation"], report["scope"]["applies_from"]),
        "",
        "This is a work list built from what the files carry. It is not a compliance",
        "determination and it is not legal advice.",
        "",
        "## Where the directory stands",
        "",
        "| Measure | Count |",
        "| --- | ---: |",
        "| Assets scanned | %d |" % counts["assets_scanned"],
        # Stated on every run, including the runs where it is zero. A coverage
        # figure that appears only when it is bad reads, on the runs where it is
        # missing, as an axis nobody checked.
        "| Files that could not be read | %d |" % counts["unreadable"],
        "| Reading as generated or manipulated | %d |" % counts["synthetic_or_indicated"],
        "| Origin undetermined | %d |" % counts["origin_undetermined"],
        "| Carrying machine-readable marking | %d |" % counts["machine_readable_marking_present"],
        "| Gaps recorded | %d (high %d, medium %d, low %d) |" % (
            counts["gaps"],
            counts["gaps_by_severity"]["high"],
            counts["gaps_by_severity"]["medium"],
            counts["gaps_by_severity"]["low"],
        ),
        "",
    ]

    if not report["gaps"]:
        lines += ["## Gaps", "", "No gaps recorded. That means nothing was found to flag in these bytes,",
                  "not that an obligation has been met.", ""]
    else:
        lines += ["## Gaps", ""]
        for level in ("high", "medium", "low"):
            batch = [g for g in report["gaps"] if g["severity"] == level]
            if not batch:
                continue
            lines += ["### %s (%d)" % (level.capitalize(), len(batch)), ""]
            for gap in batch:
                # An asset path is as attacker-shaped as a declared field: a
                # filename may legally carry a newline or a backtick, and both
                # break out of the bullet the same way an operator's title did.
                where = _render_safe(gap["asset"] or "(whole directory)", RENDER_PATH_LIMIT)
                lines += [
                    "- **%s**, %s: %s" % (_render_safe(gap["reference"]), _code_span(where),
                                          _render_safe(gap["finding"])),
                    "  - id: %s" % _code_span(_render_safe(gap["id"])),
                    "  - do: %s" % _render_safe(gap["remediation"]),
                ]
            lines.append("")

    lines += ["## What this scan did not check", ""]
    lines += ["- %s" % limit for limit in report["limits"]]
    lines.append("")
    return "\n".join(lines)


def _discard_stdout() -> None:
    """Point stdout at the null device once a write to it has already failed.

    Python flushes sys.stdout one last time as the interpreter exits, long after
    main() has returned. A second failure there prints "Exception ignored" and
    overwrites the exit code main() chose with 120 -- so the write failure this
    file classifies as exit 2 would reach the shell as neither 2 nor 1.
    Redirecting the descriptor makes that final flush a no-op.
    """
    try:
        null = os.open(os.devnull, os.O_WRONLY)
    except OSError:
        return
    try:
        os.dup2(null, sys.stdout.fileno())
    except (OSError, ValueError, AttributeError):
        # A stdout with no descriptor (a StringIO under test) cannot break a
        # pipe either, so there is nothing here to protect the exit code from.
        pass
    finally:
        os.close(null)


_STDOUT = object()  # the destination "-" names, distinct from any path


def _output_destinations(args):
    """Every artifact this invocation will write, as (flag, destination) pairs.

    The destination is what two writers would have to share to interfere: the
    resolved path for a file, or the stdout stream. Paths are resolved rather
    than compared as typed, because `out.json` and `sub/../out.json` are one
    place however differently they were spelled.
    """
    destinations = []
    if args.out:
        outdir = Path(args.out).expanduser().resolve()
        destinations.append(("--out's article50-disclosure-report.json",
                             outdir / "article50-disclosure-report.json"))
        destinations.append(("--out's article50-gaps.md", outdir / "article50-gaps.md"))
    for flag, value in (("--json", args.json), ("--gaps", args.gaps)):
        if value:
            destinations.append(
                (flag, _STDOUT if value == "-" else Path(value).expanduser().resolve()))
    return destinations


def _output_collision(args):
    """The first pair of requested artifacts that would land in one place.

    Two writers to one path do not merge: the second overwrote the first, and
    the run reported both as written either way, so `--json out.json --gaps
    out.json` left the Markdown gap list under a name a CI gate opens expecting
    the JSON report -- with nothing in the run saying the report had ever
    existed. Two writers to stdout do not overwrite but concatenate, and a JSON
    report followed by a Markdown gap list parses as neither: that is the
    documented `--json - | jq` pipeline failing at the consumer instead of here.

    Neither case has an answer this tool could pick on the operator's behalf, so
    it names the pair and refuses. A destination that already exists and is not
    a regular file is exempt: /dev/null keeps no bytes for a second write to
    overwrite, and sending one artifact there is how SKILL.md documents
    discarding it.
    """
    seen = {}
    for flag, destination in _output_destinations(args):
        if destination is not _STDOUT:
            try:
                if destination.exists() and not destination.is_file():
                    continue
            except OSError:
                # Unstattable is the write guard's problem, not this check's.
                pass
        if destination in seen:
            if destination is _STDOUT:
                return ("%s and %s would both write to stdout; one stream cannot carry "
                        "both a JSON report and a Markdown gap list" % (seen[destination], flag))
            return ("%s and %s would both write %s; the second would overwrite the first"
                    % (seen[destination], flag, destination))
        seen[destination] = flag
    return None


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog=TOOL_NAME,
        description="Scan a local directory of media assets for EU AI Act Article 50 transparency evidence. "
                    "No account, no network, no upload.",
    )
    parser.add_argument("path", help="directory to scan")
    parser.add_argument("-o", "--out", metavar="DIR",
                        help="write article50-disclosure-report.json and article50-gaps.md into DIR")
    parser.add_argument("--json", metavar="PATH", help="write the machine-readable report here ('-' for stdout)")
    parser.add_argument("--gaps", metavar="PATH", help="write the gap list here ('-' for stdout)")
    parser.add_argument("--declaration", metavar="PATH", help="operator declaration (default: article50.json in PATH)")
    parser.add_argument("--include-other", action="store_true",
                        help="also assess files whose extension is not a known media type")
    parser.add_argument("--max-bytes", type=int, default=DEFAULT_MAX_BYTES,
                        help="per-end read budget for large files, at least 1 (default %d); "
                             "it bounds every read of the asset, the hash pass included, so "
                             "sha256_scanned_regions covers the bytes named by sha256_covers "
                             "rather than the whole file; "
                             "it is not an unlimited switch, so 0 is rejected" % DEFAULT_MAX_BYTES)
    parser.add_argument("--exit-zero", action="store_true", help="exit 0 even when gaps are recorded")
    args = parser.parse_args(argv)

    root = Path(args.path).expanduser().resolve()
    if not root.is_dir():
        print("article50_scan: not a directory: %s" % root, file=sys.stderr)
        return 2
    if args.max_bytes < 1:
        # 0 is a plausible operator reading of "no limit". It is the opposite:
        # every read returns nothing and every asset reads as carrying no
        # signal. Refuse it rather than report a scan that examined no bytes.
        print("article50_scan: --max-bytes must be at least 1 (got %d)" % args.max_bytes,
              file=sys.stderr)
        return 2
    # Checked before the scan runs: this is a mistake in the invocation, and
    # reporting it after a full directory walk only delays the same rerun.
    collision = _output_collision(args)
    if collision:
        print("article50_scan: %s" % collision, file=sys.stderr)
        return 2

    try:
        report = scan(root, args.declaration, args.max_bytes, args.include_other)
    except ScanError as exc:
        print("article50_scan: %s" % exc, file=sys.stderr)
        return 2
    gap_list = render_gap_list(report)
    report_json = json.dumps(report, indent=2, sort_keys=False) + "\n"

    wrote = []
    # An artifact that could not be written is a scan that did not run to a
    # usable end: exit 2. Letting the OSError escape exited 1, which a CI gate
    # reads as "gaps found" before looking for a report that was never written.
    # Every delivery path belongs inside this guard, the bare `scan PATH` one
    # included: a write to a pipe whose reader is gone raises BrokenPipeError
    # like any other failed write, and the default path is the documented first
    # way to run the tool. What the guard cannot see is a reader that closes
    # AFTER accepting the bytes -- a report small enough for the kernel pipe
    # buffer is written successfully whatever the consumer does next, and
    # nothing afterwards tells the writer it went unread. That is why the
    # documented promise is a failed write, not an early-exiting consumer.
    #
    # UnicodeError is caught alongside OSError because a write can fail on what
    # it was asked to encode as readily as on where it was asked to put it. JSON
    # admits an unpaired surrogate (RFC 8259 sec. 8.2), UTF-8 cannot encode one,
    # and UnicodeEncodeError is a ValueError -- so an operator title carrying
    # one escaped this guard entirely and exited with a traceback and Python's
    # default 1, which a CI gate reads as "gaps found" in a report that was
    # never delivered.
    try:
        if args.out:
            outdir = Path(args.out).expanduser().resolve()
            outdir.mkdir(parents=True, exist_ok=True)
            (outdir / "article50-disclosure-report.json").write_text(report_json, encoding="utf-8")
            (outdir / "article50-gaps.md").write_text(gap_list, encoding="utf-8")
            wrote += [str(outdir / "article50-disclosure-report.json"), str(outdir / "article50-gaps.md")]
        if args.json:
            if args.json == "-":
                sys.stdout.write(report_json)
            else:
                Path(args.json).expanduser().write_text(report_json, encoding="utf-8")
                wrote.append(args.json)
        if args.gaps:
            if args.gaps == "-":
                sys.stdout.write(gap_list)
            else:
                Path(args.gaps).expanduser().write_text(gap_list, encoding="utf-8")
                wrote.append(args.gaps)
        if not (args.out or args.json or args.gaps):
            sys.stdout.write(gap_list)
        elif wrote:
            print("article50_scan: wrote %s" % ", ".join(wrote), file=sys.stderr)
        # sys.stdout.write only buffers when stdout is a pipe, so for a report
        # small enough to fit in the buffer the write syscall happened when the
        # interpreter flushed at exit -- outside this guard. A broken pipe there
        # printed "Exception ignored" and handed the shell 120, which is neither
        # the documented 2 nor a code a gate recognises. Flush where the failure
        # can still be classified.
        sys.stdout.flush()
    except (OSError, UnicodeError) as exc:
        _discard_stdout()
        print("article50_scan: cannot write the scan artifacts: %s" % exc, file=sys.stderr)
        return 2

    if report["counts"]["gaps"] and not args.exit_zero:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
